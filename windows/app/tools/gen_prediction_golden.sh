#!/bin/sh
# gen_prediction_golden.sh — regenerate windows/app/tests/fixtures/word-prediction.tsv from
# the macOS ranking code itself (App/Sources/WordPrediction.swift + the shared iOS files),
# so the C++ port (app/core/word_prediction.*) is checked against the real thing.
#   windows/app/tools/gen_prediction_golden.sh      (macOS, needs swiftc; writes the fixture)
# Compiles the Swift sources as they are (WordPrediction.swift, EnglishLite out of
# CaretSuggestions.swift) with -D VIETTELEX_CLI so the data files come from
# iOS/Keyboard/Resources; nothing is installed, the binary lives in a temp dir.
set -eu
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
KB="$ROOT/iOS/Keyboard"
OUT="$ROOT/windows/app/tests/fixtures/word-prediction.tsv"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
# WordPrediction.swift minus `import TelexCore` (the parts used here do not need it).
sed '/^import TelexCore/d' "$ROOT/App/Sources/WordPrediction.swift" > "$TMP/WordPrediction.swift"
# EnglishLite only (CaretSuggestions.swift: from its MARK to the next MARK).
{ echo 'import Foundation'
  awk '/^\/\/ MARK: - Tiếng Anh nhẹ/{on=1} /^\/\/ MARK: - 1\./{on=0} on' "$ROOT/App/Sources/CaretSuggestions.swift" \
    | sed -e 's/SwipeEnglish\.matchCase/GoldShim.matchCase/' \
          -e 's/Bundle(for: BundleToken.self).url(forResource: "enlexicon", withExtension: "bin")/VTDataFile.url("enlexicon.bin")/'
} > "$TMP/EnglishLite.swift"
cat > "$TMP/Shim.swift" <<'SWIFT'
import Foundation
enum VTDataFile {
    static func url(_ name: String) -> URL? {
        let dir = ProcessInfo.processInfo.environment["VIETTELEX_DATA_DIR"] ?? "."
        return URL(fileURLWithPath: dir + "/" + name)
    }
}
// = SwipeEnglish.matchCase (that file pulls in TelexCore).
enum GoldShim {
    static func matchCase(_ w: String, _ typed: String) -> String {
        guard let f = typed.first, f.isUppercase else { return w }
        if typed.count > 1, typed.allSatisfy({ $0.isUppercase }) { return w.uppercased() }
        return w.prefix(1).uppercased() + w.dropFirst()
    }
}
// MathHint.swift's CaretSuggestion (fields PredictionLogic.suggestion uses).
struct CaretSuggestion: Equatable {
    enum Kind: Equatable { case math, number, typo, tones, date, predict }
    let kind: Kind
    let display: String
    let replace: String
    let insert: String
}
SWIFT
cat > "$TMP/main.swift" <<'SWIFT'
import Foundation
// Cases: before-the-caret \t typed \t raw \t english(0/1) [\t filter(0/1), default 1 = "Lọc từ
// nhạy cảm" on] [\t learn]. `learn` ("Học từ bạn gõ", LearnedModel.swift) = sentences the user
// typed, "|" between them, "*N" = typed N times ("ăn tối*4|tên tôi*3"); each sentence is learned
// word by word with the 2 previous words of the same sentence as context (LearnTracker over single
// spaces). Empty = no learned model (the plain seed ranking). Output: the six input columns
// (filter always written) \t candidates (| joined).
let input = try! String(contentsOfFile: CommandLine.arguments[1], encoding: .utf8)
var out = "# word-prediction.tsv — GENERATED by windows/app/tools/gen_prediction_golden.sh from the macOS\n"
out += "# ranking (App/Sources/WordPrediction.swift + LearnedModel.swift). before\\ttyped\\traw\\tenglish\\tfilter\\tlearn\\t\n"
out += "# candidates (| joined; empty = no request / nothing). \\n in `before` = newline. learn: see the generator.\n"
let learnedFixtureSpec = "cảm ơn anh*3|tên tôi là phúc*2|ăn cơm*4|heeey you*2|gặp xyzk*3"
func learnedModel(_ spec: String) -> LearnedModel? {
    guard !spec.isEmpty else { return nil }
    let m = LearnedModel(isKnownWord: { VNSuggest.contains($0) }, now: Date(timeIntervalSince1970: 1_760_000_000))
    for part in spec.split(separator: "|") {
        var sentence = String(part), times = 1
        if let star = sentence.lastIndex(of: "*"), let n = Int(sentence[sentence.index(after: star)...]) {
            times = n
            sentence = String(sentence[..<star])
        }
        for _ in 0..<times {
            var tr = LearnTracker()
            for w in sentence.split(separator: " ") {
                if let e = tr.commit(String(w), boundary: " ") { m.record(word: e.word, after: e.prev1, prev2: e.prev2, weight: e.weight) }
            }
            if let e = tr.breakContext() { m.record(word: e.word, after: e.prev1, prev2: e.prev2, weight: e.weight) }
        }
    }
    return m
}
for line in input.split(separator: "\n", omittingEmptySubsequences: false) {
    if line.isEmpty || line.hasPrefix("#") { continue }
    let f = line.split(separator: "\t", omittingEmptySubsequences: false).map(String.init)
    let before = f[0].replacingOccurrences(of: "\\n", with: "\n")
    let filter = f.count > 4 ? f[4] != "0" : true
    let learn = f.count > 5 ? f[5] : ""
    var c: [String] = []
    if let r = PredictionLogic.request(before: before, typed: f[1], english: f[3] == "1") {
        c = PredictionModel.shared.candidates(r, raw: f[2], filterSensitive: filter, learned: learnedModel(learn))
    }
    out += "\(f[0])\t\(f[1])\t\(f[2])\t\(f[3])\t\(filter ? 1 : 0)\t\(learn)\t\(c.joined(separator: "|"))\n"
}
try! out.write(toFile: CommandLine.arguments[2], atomically: true, encoding: .utf8)
// The same model on disk (VTL2, UserLMCodec): learned_words.cpp must decode it and encode the
// same record sequence to the very same bytes.
let bin = learnedModel(learnedFixtureSpec)!.snapshot().encoded()
try! bin.write(to: URL(fileURLWithPath: CommandLine.arguments[3]))
SWIFT
swiftc -O -D VIETTELEX_CLI -o "$TMP/gold" "$TMP/main.swift" "$TMP/Shim.swift" "$TMP/WordPrediction.swift" \
  "$TMP/EnglishLite.swift" "$ROOT/App/Sources/SeedNextData.swift" "$ROOT/App/Sources/LearnedModel.swift" "$KB/UserLMTables.swift" "$KB/VNSuggest.swift" "$KB/VNLexicon2.swift" "$KB/SyllableLM.swift" \
  "$KB/SwipeLexicon.swift" "$KB/SeedData.swift" "$KB/DisplayCase.swift" "$KB/SensitiveWords.swift" \
  "$KB/SuggestionSupport.swift"
VIETTELEX_DATA_DIR="$KB/Resources" "$TMP/gold" "$ROOT/windows/app/tools/prediction-cases.tsv" "$OUT" \
  "$ROOT/windows/app/tests/fixtures/learned-words.bin"
echo "wrote $OUT and windows/app/tests/fixtures/learned-words.bin"
