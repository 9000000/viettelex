#!/usr/bin/env python3
"""gen_seed_unigrams.py — iOS/Keyboard/SeedData.swift `unigrams` -> windows/app/core/seed_unigrams.inc.

Word prediction ranks completions with the seed counts like macOS (WordPrediction.swift
PredictionModel.count). The table is one packed string + offsets + counts (UTF-8 byte order) searched
in place: no heap, no start-up cost. app_tests (prediction_seed_matches_swift) re-parses the
Swift file and fails when this output is stale.

    python3 windows/app/tools/gen_seed_unigrams.py
"""
import os
import re
import unicodedata

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
SRC = os.path.join(ROOT, "iOS", "Keyboard", "SeedData.swift")
OUT = os.path.join(ROOT, "windows", "app", "core", "seed_unigrams.inc")


def unigrams(text):
    start = text.index("static var unigrams")
    end = text.index("] }", start)
    pairs = re.findall(r'"([^"]+)":\s*(\d+)', text[start:end])
    out = {}
    for w, c in pairs:
        if w in out:
            raise SystemExit("duplicate seed word: " + w)
        if unicodedata.normalize("NFC", w) != w:
            raise SystemExit("not NFC: " + w)
        out[w] = int(c)
    return out


def main():
    with open(SRC, encoding="utf-8") as f:
        seed = unigrams(f.read())
    rows = sorted(seed.items(), key=lambda kv: kv[0].encode("utf-8"))
    blob = b""
    offs = []
    for w, _ in rows:
        offs.append(len(blob))
        blob += w.encode("utf-8") + b"\0"
    if len(blob) > 0xFFFF or max(c for _, c in rows) > 255:
        raise SystemExit("table no longer fits uint16 offsets / uint8 counts")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by windows/app/tools/gen_seed_unigrams.py from iOS/Keyboard/SeedData.swift\n")
        f.write("// (unigrams, %d entries sorted by UTF-8 bytes, %d bytes of text). Do not edit.\n" % (len(rows), len(blob)))
        f.write("constexpr int kSeedCount = %d;\n" % len(rows))
        f.write("const char kSeedWords[] =\n")
        line = '    "'
        for w, _ in rows:
            item = w + "\\000"  # 3-digit octal: a following digit cannot extend it
            if len(line) + len(item) > 110:
                f.write(line + '"\n')
                line = '    "'
            line += item
        f.write(line + '";\n')
        f.write("const uint16_t kSeedOff[] = {\n")
        for i in range(0, len(offs), 16):
            f.write("    " + ", ".join(str(o) for o in offs[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write("const uint8_t kSeedN[] = {\n")
        for i in range(0, len(rows), 24):
            f.write("    " + ", ".join(str(c) for _, c in rows[i:i + 24]) + ",\n")
        f.write("};\n")
    print("wrote %s (%d)" % (OUT, len(rows)))


if __name__ == "__main__":
    main()
