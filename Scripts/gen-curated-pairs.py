#!/usr/bin/env python3
"""gen-curated-pairs.py — Scripts/curated-pairs.txt → bảng cặp chọn tay cho mọi nền tảng:

  iOS/Keyboard/CuratedPairs.swift                                   (iOS + macOS + Linux)
  android/keyboard/src/main/kotlin/com/viettelex/keyboard/CuratedPairs.kt
  windows/engine/src/curated_pairs.inc                              (add_tones.cpp)

Mỗi bảng = danh sách khoá đã sắp xếp (byte UTF-8): cặp "a b", bộ ba "x a b" (cặp a→b chỉ
tính sau x). Logic tra cứu viết tay ở từng nền tảng (giống hệt nhau). KHÔNG sửa file sinh ra.

  Scripts/gen-curated-pairs.py           ghi ba file
  Scripts/gen-curated-pairs.py --check   so với file đã commit; khác ⇒ exit 1
"""
import os, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Scripts", "curated-pairs.txt")
OUT_SWIFT = os.path.join(ROOT, "iOS", "Keyboard", "CuratedPairs.swift")
OUT_KT = os.path.join(ROOT, "android", "keyboard", "src", "main", "kotlin", "com", "viettelex", "keyboard",
                      "CuratedPairs.kt")
OUT_INC = os.path.join(ROOT, "windows", "engine", "src", "curated_pairs.inc")


def parse():
    pairs, triples, nextonly = set(), set(), set()
    for n, line in enumerate(open(SRC, encoding="utf-8"), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        assert line == unicodedata.normalize("NFC", line) and line == line.lower(), f"dòng {n}: NFC chữ thường"
        ctx, only = None, line.startswith("~")
        if only:
            line = line[1:].strip()
        if line.startswith("["):
            ctx, line = line[1:].split("]", 1)
            ctx = ctx.strip()
        ws = line.split()
        assert ws and all(" " not in w for w in ws), f"dòng {n}"
        if ctx is not None:
            assert len(ws) == 2, f"dòng {n}: [x] a b"
            triples.add(f"{ctx} {ws[0]} {ws[1]}")
        else:
            assert len(ws) >= 2, f"dòng {n}: cần ≥ 2 âm tiết"
            for a, b in zip(ws, ws[1:]):
                (nextonly if only else pairs).add(f"{a} {b}")
    key = lambda s: s.encode("utf-8")
    nextonly -= pairs
    return sorted(pairs, key=key), sorted(triples, key=key), sorted(nextonly, key=key)


HEAD = "GENERATED by Scripts/gen-curated-pairs.py from Scripts/curated-pairs.txt — do not edit."


def rows(keys, fmt, per=4, indent="        "):
    out, cur = [], []
    for k in keys:
        cur.append(fmt(k))
        if len(cur) == per:
            out.append(indent + " ".join(cur)); cur = []
    if cur:
        out.append(indent + " ".join(cur))
    return "\n".join(out)


def swift(pairs, triples, nextonly):
    q = lambda k: f'"{k}",'
    return f"""// CuratedPairs.swift — {HEAD}
// Cặp âm tiết chọn tay CHỈ để phân định dấu (AddTones, bung dấu từ vuốt, xếp gợi ý đang gõ dở) —
// không phải seed từ kế tiếp. Dùng chung iOS / macOS / Linux; song sinh CuratedPairs.kt +
// windows/engine/src/curated_pairs.inc. Ý nghĩa + lý do từng nhóm: Scripts/curated-pairs.txt.
enum CuratedPairs {{
    /// "a b": cộng cho a → b mọi nơi.
    static let pairs: Set<String> = [
{rows(pairs, q)}
    ]
    /// "x a b": cộng cho a → b chỉ khi âm tiết trước a là x.
    static let triples: Set<String> = [
{rows(triples, q)}
    ]
    /// "a b": chỉ cho vuốt / gợi ý đang gõ (`next`), không cho Thêm dấu.
    static let nextOnly: Set<String> = [
{rows(nextonly, q)}
    ]
    /// "x a" của mọi bộ ba — lọc nhanh trước khi ghép khoá đủ.
    static let tripleHeads: Set<String> = Set(triples.map {{ k in
        let p = k.split(separator: " "); return p[0] + " " + p[1]
    }})
    /// "a b" của mọi bộ ba.
    static let tripleTails: Set<String> = Set(triples.map {{ k in
        let p = k.split(separator: " "); return p[1] + " " + p[2]
    }})

    /// Chuyển `a` → `b` (chữ thường, NFC) có trong bảng; `x` = âm tiết trước `a` (nil = không biết).
    static func has(_ x: String?, _ a: String, _ b: String) -> Bool {{
        if pairs.contains(a + " " + b) {{ return true }}
        if let x, triples.contains(x + " " + a + " " + b) {{ return true }}
        return false
    }}

    /// Như `has` nhưng gồm cả cặp chỉ cho vuốt (`nextOnly`) — vuốt / gợi ý đang gõ.
    static func swipe(_ x: String?, _ a: String, _ b: String) -> Bool {{
        has(x, a, b) || nextOnly.contains(a + " " + b)
    }}

    /// `words` (từ kế tiếp cá nhân/seed) + các từ chọn tay sau (`prev2`, `prev`) chưa có — ngữ cảnh
    /// `next` của vuốt và của xếp gợi ý đang gõ dở. prev nil ⇒ giữ nguyên.
    static func withNext(_ words: [String], after prev: String?, prev2: String?) -> [String] {{
        guard let prev else {{ return words }}
        let extra = next(after: prev, prev2: prev2).filter {{ !words.contains($0) }}
        return extra.isEmpty ? words : words + extra
    }}

    /// `a` → `b` có trong bảng ở BẤT KỲ ngữ cảnh nào (cặp hoặc đuôi bộ ba).
    static func anyContext(_ a: String, _ b: String) -> Bool {{
        let k = a + " " + b
        return pairs.contains(k) || tripleTails.contains(k)
    }}

    /// Có bộ ba nào bắt đầu bằng (x, a) không.
    static func hasTriple(_ x: String, _ a: String) -> Bool {{ tripleHeads.contains(x + " " + a) }}

    /// Các từ được cộng sau (`prev2`, `prev`) — ngữ cảnh vuốt / gợi ý đang gõ (chữ thường).
    static func next(after prev: String, prev2: String?) -> [String] {{
        let p = prev.lowercased(), x = prev2?.lowercased()
        var out: [String] = []
        for k in pairs.union(nextOnly) where k.hasPrefix(p + " ") {{ out.append(String(k.dropFirst(p.count + 1))) }}
        if let x {{
            let h = x + " " + p + " "
            for k in triples where k.hasPrefix(h) {{ out.append(String(k.dropFirst(h.count))) }}
        }}
        return out.sorted()
    }}
}}
"""


def kotlin(pairs, triples, nextonly):
    q = lambda k: f'"{k}",'
    return f"""// CuratedPairs.kt — {HEAD}
// Song sinh iOS/Keyboard/CuratedPairs.swift (cùng dữ liệu, cùng logic). Cặp âm tiết chọn tay CHỈ để
// phân định dấu — không phải seed từ kế tiếp. Lý do từng nhóm: Scripts/curated-pairs.txt.
package com.viettelex.keyboard

object CuratedPairs {{
    /** "a b": cộng cho a → b mọi nơi. */
    val pairs: Set<String> = hashSetOf(
{rows(pairs, q)}
    )

    /** "x a b": cộng cho a → b chỉ khi âm tiết trước a là x. */
    val triples: Set<String> = hashSetOf(
{rows(triples, q)}
    )

    /** "a b": chỉ cho vuốt / gợi ý đang gõ ([next]), không cho Thêm dấu. */
    val nextOnly: Set<String> = hashSetOf(
{rows(nextonly, q)}
    )

    private val tripleHeads: Set<String> = triples.mapTo(HashSet()) {{ it.split(' ').let {{ p -> p[0] + " " + p[1] }} }}
    private val tripleTails: Set<String> = triples.mapTo(HashSet()) {{ it.split(' ').let {{ p -> p[1] + " " + p[2] }} }}

    /** Chuyển [a] → [b] (chữ thường, NFC) có trong bảng; [x] = âm tiết trước [a] (null = không biết). */
    fun has(x: String?, a: String, b: String): Boolean =
        "$a $b" in pairs || (x != null && "$x $a $b" in triples)

    /** Như [has] nhưng gồm cả cặp chỉ cho vuốt ([nextOnly]) — vuốt / gợi ý đang gõ. */
    fun swipe(x: String?, a: String, b: String): Boolean = has(x, a, b) || "$a $b" in nextOnly

    /** [words] (từ kế tiếp cá nhân/seed) + các từ chọn tay sau ([prev2], [prev]) chưa có — ngữ cảnh
     *  `next` của vuốt và của xếp gợi ý đang gõ dở. prev null ⇒ giữ nguyên. */
    fun withNext(words: List<String>, prev: String?, prev2: String?): List<String> {{
        if (prev == null) return words
        val extra = next(prev, prev2).filter {{ it !in words }}
        return if (extra.isEmpty()) words else words + extra
    }}

    /** [a] → [b] có trong bảng ở BẤT KỲ ngữ cảnh nào (cặp hoặc đuôi bộ ba). */
    fun anyContext(a: String, b: String): Boolean = "$a $b".let {{ it in pairs || it in tripleTails }}

    /** Có bộ ba nào bắt đầu bằng ([x], [a]) không. */
    fun hasTriple(x: String, a: String): Boolean = "$x $a" in tripleHeads

    /** Các từ được cộng sau ([prev2], [prev]) — ngữ cảnh vuốt / gợi ý đang gõ (chữ thường). */
    fun next(prev: String, prev2: String?): List<String> {{
        val p = prev.lowercase()
        val out = ArrayList<String>()
        for (k in pairs) if (k.startsWith("$p ")) out.add(k.substring(p.length + 1))
        for (k in nextOnly) if (k.startsWith("$p ")) out.add(k.substring(p.length + 1))
        if (prev2 != null) {{
            val h = "${{prev2.lowercase()}} $p "
            for (k in triples) if (k.startsWith(h)) out.add(k.substring(h.length))
        }}
        return out.sorted()
    }}
}}
"""


def cpp(pairs, triples, nextonly):
    q = lambda k: f'"{k}",'
    return f"""// curated_pairs.inc — {HEAD}
// Included by add_tones.cpp (namespace vtx::addtones). Twin of iOS/Keyboard/CuratedPairs.swift:
// sorted (UTF-8 byte order) keys "a b" (pair, everywhere) and "x a b" (a → b only after x).
// The swipe/suggestion-only entries (CuratedPairs.nextOnly) are not needed by Thêm dấu.
const char* const kCuratedPairs[] = {{
{rows(pairs, q, indent="    ")}
}};
const char* const kCuratedTriples[] = {{
{rows(triples, q, indent="    ")}
}};
"""


def main():
    pairs, triples, nextonly = parse()
    outs = {OUT_SWIFT: swift(pairs, triples, nextonly), OUT_KT: kotlin(pairs, triples, nextonly),
            OUT_INC: cpp(pairs, triples, nextonly)}
    if "--check" in sys.argv:
        bad = [p for p, s in outs.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != s]
        if bad:
            print("curated pairs tables are stale: run Scripts/gen-curated-pairs.py\n  " + "\n  ".join(bad),
                  file=sys.stderr)
            sys.exit(1)
        print(f"curated pairs OK ({len(pairs)} cặp, {len(triples)} bộ ba, {len(nextonly)} cặp chỉ vuốt)")
        return
    for p, s in outs.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(s)
    print(f"{len(pairs)} cặp, {len(triples)} bộ ba, {len(nextonly)} cặp chỉ vuốt → {len(outs)} file")


if __name__ == "__main__":
    main()
